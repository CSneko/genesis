/**
 * Resolve known upstream tool labels, leaving unknown names available as diagnostic text.
 * @param name - Upstream tool name.
 * @returns Its locale key when this viewer has a label.
 */
export function actionKey(name: string): BrowserPreviewKey | undefined {
  const key = `action.${name}`
  return Object.hasOwn(en, key) ? key as BrowserPreviewKey : undefined
}
